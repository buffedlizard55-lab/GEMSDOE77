def md_to_html(md: str) -> str:
    """Tiny Markdown subset (headings, paragraphs, bullet lists, pipe tables, inline code) for the policy page."""
    import re
    out, para, in_ul, in_tbl = [], [], False, False

    def flush():
        nonlocal para
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>")
            para = []

    def inline(t):
        t = e(t)
        t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
        t = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)
        t = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2">\1</a>', t)
        return t

    for line in md.splitlines():
        st = line.strip()
        if st.startswith("|"):
            flush()
            cells = [c.strip() for c in st.strip("|").split("|")]
            if all(set(c) <= set("-: ") for c in cells):
                continue
            if not in_tbl:
                out.append("<table>")
                in_tbl = True
                out.append("<tr>" + "".join(f"<th>{inline(c)}</th>" for c in cells) + "</tr>")
            else:
                out.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in cells) + "</tr>")
            continue
        if in_tbl:
            out.append("</table>")
            in_tbl = False
        if st.startswith("#"):
            flush()
            if in_ul:
                out.append("</ul>")
                in_ul = False
            lvl = len(st) - len(st.lstrip("#"))
            out.append(f"<h{min(lvl, 3)}>{inline(st[lvl:].strip())}</h{min(lvl, 3)}>")
        elif st.startswith(("- ", "* ")) or re.match(r"^\d+\. ", st):
            flush()
            if not in_ul:
                out.append("<ul>")
                in_ul = True
            item = re.sub(r"^(\d+\. |- |\* )", "", st)
            out.append(f"<li>{inline(item)}</li>")
        elif not st:
            flush()
            if in_ul:
                out.append("</ul>")
                in_ul = False
        else:
            para.append(st)
    flush()
    if in_ul:
        out.append("</ul>")
    if in_tbl:
        out.append("</table>")
    return "\n".join(out)


